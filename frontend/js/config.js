/* 载波侦听（CCA）门限：外部 BSS 强于这个值才会真的抢走空口时间 */
const CCA = -82;

/* 2.4 GHz 在中国只有这三条互不重叠的信道，是物理事实，算法绕不过去 */
const CH24 = [1, 6, 11];

/* 5 GHz 非 DFS 段的 20 MHz 信道：不受雷达检测影响，规划时优先用这一段 */
const CH5 = [36, 40, 44, 48, 149, 153, 157, 161, 165];

/* 信道 → 中心频率（MHz）。表里没有的信道现场换算，覆盖 2.4 / 5 / 6 GHz。 */
const FREQ = {1:2412, 2:2417, 3:2422, 4:2427, 5:2432, 6:2437, 7:2442, 8:2447,
              9:2452, 10:2457, 11:2462, 12:2467, 13:2472, 14:2484,
              36:5180, 40:5200, 44:5220, 48:5240, 52:5260, 56:5280, 60:5300,
              64:5320, 100:5500, 104:5520, 108:5540, 112:5560, 116:5580,
              120:5600, 124:5620, 128:5640, 132:5660, 136:5680, 140:5700,
              144:5720, 149:5745, 153:5765, 157:5785, 161:5805, 165:5825,
              169:5845, 173:5865, 177:5885};

function freqOf(channel, band) {
  if (FREQ[channel]) return FREQ[channel];
  if (band === '6') return 5950 + 5 * channel;
  if (channel >= 32) return 5000 + 5 * channel;
  return 2407 + 5 * channel;
}

/* 各频段的展示名与配色 */
const BAND_META = {
  '2.4': { label: '2.4 GHz', tag: 'gray' },
  '5':   { label: '5 GHz',   tag: 'blue' },
  '6':   { label: '6 GHz',   tag: 'violet' }
};

function bandLabel(band) {
  return (BAND_META[band] || { label: band + ' GHz' }).label;
}
function bandTagClass(band) {
  return (BAND_META[band] || { tag: 'gray' }).tag;
}

